import esbuild from 'esbuild'
import process from 'process'
import builtins from 'builtin-modules'
import fs from 'fs-extra'
import path from 'path'

// Leitura opcional de .env local sem dependências externas
const loadEnvFile = () => {
    const envPath = path.resolve('.env')
    if (!fs.existsSync(envPath)) return

    try {
        const content = fs.readFileSync(envPath, 'utf-8')
        for (const line of content.split(/\r?\n/)) {
            const trimmed = line.trim()
            if (!trimmed || trimmed.startsWith('#')) continue
            const separatorIdx = trimmed.indexOf('=')
            if (separatorIdx === -1) continue

            const key = trimmed.slice(0, separatorIdx).trim()
            let val = trimmed.slice(separatorIdx + 1).trim()
            if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
                val = val.slice(1, -1)
            }
            if (!process.env[key]) {
                process.env[key] = val
            }
        }
    } catch (err) {
        console.warn('Aviso: Falha ao carregar .env:', err.message)
    }
}

loadEnvFile()

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`

const prod = process.argv[2] === 'production'
const distDir = 'dist'
const vaultPluginPath = process.env.OBSIDIAN_VAULT_PATH?.trim()

const buildPlugin = async () => {
    try {
        // Garante que a pasta dist exista limpa
        await fs.ensureDir(distDir)

        // Compila o main.js direto na pasta dist
        await esbuild.build({
            banner: { js: banner },
            entryPoints: ['src/main.ts'],
            bundle: true,
            external: ['obsidian', 'electron', ...builtins],
            format: 'cjs',
            target: 'es2018',
            logLevel: 'info',
            sourcemap: prod ? false : 'inline',
            treeShaking: true,
            outfile: path.join(distDir, 'main.js')
        })

        // Copia os metadados necessários para rodar o plugin
        await fs.copyFile('manifest.json', path.join(distDir, 'manifest.json'))

        if (await fs.pathExists('styles.css')) {
            await fs.copyFile('styles.css', path.join(distDir, 'styles.css'))
        }

        console.log(`\nBuild concluído! Arquivos prontos em: ./${distDir}/`)

        // Se houver diretório de vault configurado via .env / env var, realiza auto-deploy
        if (vaultPluginPath) {
            await fs.ensureDir(vaultPluginPath)
            await fs.copyFile(path.join(distDir, 'main.js'), path.join(vaultPluginPath, 'main.js'))
            await fs.copyFile(path.join(distDir, 'manifest.json'), path.join(vaultPluginPath, 'manifest.json'))

            if (await fs.pathExists('styles.css')) {
                await fs.copyFile(path.join(distDir, 'styles.css'), path.join(vaultPluginPath, 'styles.css'))
            }

            console.log(`Plugin copiado com sucesso para o vault: ${vaultPluginPath}\n`)
        } else {
            console.log('OBSIDIAN_VAULT_PATH não configurado. Para copiar automaticamente, configure seu .env (veja .env.example).\n')
        }
    } catch (e) {
        console.error(e)
        process.exit(1)
    }
}

buildPlugin()

